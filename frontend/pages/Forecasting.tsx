
import React, { useState, useEffect } from 'react';
import { useData } from '../store/DataContext';
import { useAuth, useAuthFetch } from '../store/AuthContext';
import { TrendingUp, Clock, Target, Info, Loader2, AlertCircle, RefreshCw, Brain } from 'lucide-react';
import FiltersBar from '../components/FiltersBar';
import { 
  ComposedChart, Line, Area, XAxis, YAxis, CartesianGrid, Tooltip, ResponsiveContainer, Legend
} from 'recharts';

const Forecasting: React.FC = () => {
  const {
    forecast: contextForecast,
    filters,
    setFilters,
    clearFilters,
    cityOptions,
    productOptions,
  } = useData();
  const { user } = useAuth();
  const authFetch = useAuthFetch();
  
  // State
  const [forecast, setForecast] = useState<any[]>([]);
  const [loading, setLoading] = useState(false);
  const [generating, setGenerating] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [modelInfo, setModelInfo] = useState<{
    model_type: string;
    metrics: { MAE?: number; RMSE?: number; MAPE?: number };
    explanation?: any;
  } | null>(null);

  // Fetch latest forecast on mount
  useEffect(() => {
    fetchLatestForecast();
  }, [user, contextForecast]);

  const fetchLatestForecast = async () => {
    setLoading(true);
    setError(null);

    try {
      // Use context data directly (comes from /api/monthly-sales)
      if (contextForecast && contextForecast.length > 0) {
        setForecast(contextForecast);
        setModelInfo({
          model_type: 'Prophet',
          metrics: {},
          explanation: null,
        });
      } else {
        setForecast([]);
      }
    } catch (e) {
      console.error('Failed to fetch forecast:', e);
      setForecast([]);
    } finally {
      setLoading(false);
    }
  };

  const generateNewForecast = async () => {
    setGenerating(true);
    setError(null);

    try {
      // Refresh data from the server
      // The forecast is generated by running 03_forecasting.py script
      // For now, just reload the context data
      await new Promise(resolve => setTimeout(resolve, 1000));
      
      if (contextForecast && contextForecast.length > 0) {
        setForecast(contextForecast);
        setModelInfo({
          model_type: 'Linear Regression',
          metrics: {},
          explanation: null,
        });
      } else {
        setError('No forecast data available. Please run the forecasting script first.');
      }
    } catch (e) {
      setError(e instanceof Error ? e.message : 'Failed to generate forecast');
    } finally {
      setGenerating(false);
    }
  };

  // Remove unused pollTaskStatus function since we're not using async tasks

  const nextMonthForecast = forecast.find(f => !f.actual)?.forecast || forecast[0]?.forecast || 0;
  const lastActual = forecast.filter(f => f.actual).slice(-1)[0]?.actual || 0;
  const growthRate = lastActual ? ((nextMonthForecast - lastActual) / lastActual * 100).toFixed(1) : '0';
  const hasComparison = forecast?.some((p) => p.previous_actual !== undefined && p.previous_actual !== null);

  return (
    <div className="space-y-8 animate-in fade-in duration-500">
      <div className="flex justify-between items-start">
        <div>
          <h2 className="text-2xl font-bold tracking-tight">Predictive Forecasting</h2>
          <p className="text-text-secondary">AI-powered sales projections using Prophet with seasonality detection.</p>
        </div>
        <div className="flex gap-4 items-center">
          <button
            onClick={generateNewForecast}
            disabled={generating}
            className="flex items-center gap-2 px-4 py-2 bg-primary text-white rounded-xl font-semibold hover:bg-primary/90 disabled:opacity-50 disabled:cursor-not-allowed transition-all"
          >
            {generating ? (
              <>
                <Loader2 size={18} className="animate-spin" />
                Generating...
              </>
            ) : (
              <>
                <RefreshCw size={18} />
                Generate Forecast
              </>
            )}
          </button>
          <div className="bg-primary/5 border border-primary/20 px-4 py-2 rounded-xl flex items-center gap-3">
            <div className="p-1.5 bg-primary/10 rounded-lg text-primary">
              <TrendingUp size={18} />
            </div>
            <div>
              <p className="text-xs text-text-secondary font-medium">Predicted Growth</p>
              <p className="text-sm font-bold text-primary">+{growthRate}% next month</p>
            </div>
          </div>
        </div>
      </div>

      <FiltersBar
        filters={filters}
        setFilters={setFilters}
        clearFilters={clearFilters}
        cityOptions={cityOptions}
        productOptions={productOptions}
      />

      {/* Error Display */}
      {error && (
        <div className="flex items-center gap-2 p-4 bg-red-50 border border-red-200 rounded-xl text-red-700">
          <AlertCircle size={18} />
          <span>{error}</span>
        </div>
      )}

      <div className="grid grid-cols-1 md:grid-cols-3 gap-6">
        <div className="bg-card-light dark:bg-card-dark p-6 rounded-2xl border border-slate-200 dark:border-slate-800 shadow-sm">
          <div className="flex items-center gap-3 mb-4 text-text-secondary">
            <Clock size={20} />
            <span className="text-sm font-semibold uppercase tracking-wider">Horizon</span>
          </div>
          <p className="text-2xl font-bold">6 Months</p>
          <p className="text-xs text-text-secondary mt-1">Short-term projection window</p>
        </div>
        <div className="bg-card-light dark:bg-card-dark p-6 rounded-2xl border border-slate-200 dark:border-slate-800 shadow-sm">
          <div className="flex items-center gap-3 mb-4 text-text-secondary">
            <Target size={20} />
            <span className="text-sm font-semibold uppercase tracking-wider">Accuracy (MAPE)</span>
          </div>
          <p className="text-2xl font-bold">
            {modelInfo?.metrics?.MAPE ? `${modelInfo.metrics.MAPE.toFixed(1)}%` : '--'}
          </p>
          <p className="text-xs text-text-secondary mt-1">Mean Absolute Percentage Error</p>
        </div>
        <div className="bg-card-light dark:bg-card-dark p-6 rounded-2xl border border-slate-200 dark:border-slate-800 shadow-sm">
          <div className="flex items-center gap-3 mb-4 text-text-secondary">
            <Brain size={20} />
            <span className="text-sm font-semibold uppercase tracking-wider">Model Type</span>
          </div>
          <p className="text-2xl font-bold">{modelInfo?.model_type || 'Prophet'}</p>
          <p className="text-xs text-text-secondary mt-1">Additive time-series with seasonality</p>
        </div>
      </div>

      <div className="bg-card-light dark:bg-card-dark p-8 rounded-2xl border border-slate-200 dark:border-slate-800 shadow-sm">
        <div className="flex justify-between items-center mb-8">
          <h3 className="text-lg font-bold">Sales Volume Forecast with Confidence Intervals</h3>
          <div className="flex items-center gap-4 text-sm">
            <div className="flex items-center gap-2">
              <div className="w-3 h-3 bg-blue-500 rounded-full"></div>
              <span className="text-text-secondary">Forecast</span>
            </div>
            <div className="flex items-center gap-2">
              <div className="w-3 h-3 bg-blue-200 rounded-full"></div>
              <span className="text-text-secondary">95% Confidence Band</span>
            </div>
          </div>
        </div>

        <div className="flex flex-wrap gap-3 text-xs text-text-secondary dark:text-text-secondaryDark mb-4">
          {hasComparison && (
            <div className="flex items-center gap-2">
              <span className="w-6 h-[2px]" style={{ borderTop: '2px dashed #94A3B8' }} />
              Previous period
            </div>
          )}
          <div className="flex items-center gap-2">
            <span className="w-6 h-[2px] bg-primary" />
            Actual
          </div>
          <div className="flex items-center gap-2">
            <span className="w-6 h-[2px]" style={{ borderTop: '2px dashed #64748B' }} />
            Forecast
          </div>
          <div className="flex items-center gap-2">
            <span className="w-6 h-[2px] bg-blue-200" />
            Confidence band
          </div>
        </div>
        
        {loading ? (
          <div className="h-[450px] flex items-center justify-center">
            <Loader2 size={40} className="animate-spin text-primary" />
          </div>
        ) : forecast && forecast.length > 0 ? (
          <div className="h-[450px]">
            <ResponsiveContainer width="100%" height="100%">
              <ComposedChart data={forecast}>
                <CartesianGrid strokeDasharray="3 3" vertical={false} stroke="#e2e8f0" />
                <XAxis dataKey="date" axisLine={false} tickLine={false} tick={{fontSize: 13}} dy={15} />
                <YAxis axisLine={false} tickLine={false} tick={{fontSize: 13}} tickFormatter={(v) => `$${(v/1000).toFixed(0)}k`} />
                <Tooltip 
                  cursor={{ stroke: '#2563EB', strokeWidth: 1, strokeDasharray: '4 4' }}
                  contentStyle={{ borderRadius: '12px', border: 'none', boxShadow: '0 20px 25px -5px rgba(0, 0, 0, 0.1)' }}
                  formatter={(value: any) => [`$${Number(value).toLocaleString()}`, '']}
                />
                <Legend verticalAlign="top" height={36}/>

                {hasComparison && (
                  <Line
                    name="Previous Period"
                    type="monotone"
                    dataKey="previous_actual"
                    stroke="#94A3B8"
                    strokeWidth={2}
                    strokeDasharray="4 4"
                    dot={false}
                  />
                )}
                
                {/* Confidence Band (95% interval) */}
                <Area 
                  name="95% Confidence Band"
                  type="monotone" 
                  dataKey="forecast_upper"
                  fill="#3B82F6" 
                  fillOpacity={0.1} 
                  stroke="transparent"
                />
                <Area 
                  type="monotone" 
                  dataKey="forecast_lower"
                  fill="#FFFFFF" 
                  fillOpacity={1} 
                  stroke="transparent"
                />

                {/* Historical Actuals */}
                <Area 
                  name="Historical Actuals"
                  type="monotone" 
                  dataKey="actual" 
                  fill="#2563EB" 
                  fillOpacity={0.05} 
                  stroke="transparent" 
                />

                {/* Forecast Line */}
                <Line 
                  name="Prophet Forecast"
                  type="monotone" 
                  dataKey="forecast" 
                  stroke="#3B82F6" 
                  strokeWidth={3} 
                  dot={{ r: 5, fill: '#3B82F6', strokeWidth: 2, stroke: '#fff' }}
                />

                {/* Observed Data */}
                <Line 
                  name="Observed Data"
                  type="monotone" 
                  dataKey="actual" 
                  stroke="#10B981" 
                  strokeWidth={3} 
                  dot={{ r: 5, fill: '#10B981', strokeWidth: 2, stroke: '#fff' }}
                />
              </ComposedChart>
            </ResponsiveContainer>
          </div>
        ) : (
          <div className="h-[450px] flex items-center justify-center bg-slate-50 dark:bg-slate-900/50 rounded-lg border border-dashed border-slate-300 dark:border-slate-700">
            <div className="text-center">
              <p className="text-slate-600 dark:text-slate-400 font-medium">No forecast data available</p>
              <p className="text-slate-500 dark:text-slate-500 text-sm mt-1">Click "Generate Forecast" to create predictions</p>
            </div>
          </div>
        )}
        
        {/* Explainability Section */}
        {modelInfo?.explanation && (
          <div className="mt-8 space-y-4">
            <h4 className="font-bold text-md flex items-center gap-2">
              <Brain size={18} />
              Forecast Explanation
            </h4>
            
            <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
              {modelInfo.explanation.forecast_summary && (
                <div className="p-4 bg-slate-50 dark:bg-slate-900/50 rounded-xl border border-slate-200 dark:border-slate-800">
                  <p className="text-sm font-semibold mb-2">Summary</p>
                  <p className="text-sm text-text-secondary">
                    {modelInfo.explanation.forecast_summary.interpretation}
                  </p>
                </div>
              )}
              
              {modelInfo.explanation.trend_analysis && (
                <div className="p-4 bg-slate-50 dark:bg-slate-900/50 rounded-xl border border-slate-200 dark:border-slate-800">
                  <p className="text-sm font-semibold mb-2">Trend Analysis</p>
                  <p className="text-sm text-text-secondary">
                    {modelInfo.explanation.trend_analysis.interpretation}
                  </p>
                </div>
              )}
            </div>
            
            {modelInfo.explanation.recommendations && modelInfo.explanation.recommendations.length > 0 && (
              <div className="p-4 bg-blue-50 dark:bg-blue-900/20 rounded-xl border border-blue-200 dark:border-blue-800 flex items-start gap-3">
                <div className="mt-1 text-primary"><Info size={18} /></div>
                <div>
                  <p className="text-sm font-bold">Recommendations</p>
                  <ul className="text-sm text-text-secondary mt-1 list-disc list-inside">
                    {modelInfo.explanation.recommendations.map((rec: string, idx: number) => (
                      <li key={idx}>{rec}</li>
                    ))}
                  </ul>
                </div>
              </div>
            )}
          </div>
        )}
      </div>
    </div>
  );
};

export default Forecasting;
